/**
 * The manager's side of the native PostgreSQL cluster it owns
 * (documentation/native_postgres.md). Everything that needs root happens in
 * the privileged helper (`packages`, `postgres.cluster.*`, apps/manager/privileged);
 * everything the manager may look at without root (the distribution, the
 * packages, the clusters, the storage, the ports) is the read-only inventory in
 * `@goobster/core/db/native`. This file composes the two with the manager's
 * settings, the instance record (`<store>/native-postgres.json`) and the #338
 * connection library, which probes the application role like for any server.
 *
 * Secrets: the application password is generated by the caller and passed in.
 * Only its SCRAM-SHA-256 verifier reaches the helper (stdin of one process,
 * never an argv, a record, a plan, a journal, a result or a log line). The
 * application URL is staged in the overlay under a key that is never merged
 * into an environment (environment.js STAGED_KEYS) until `database.connect`
 * writes the live one.
 */

