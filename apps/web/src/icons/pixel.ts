/** Pixel markup: one rect per lit cell, two cells per grid unit on the 24 grid. */
export function pixelMarkup(name: GlyphName): string {
    const rows = PIXEL[name].trim().split('\n');
    const cell = 24 / 12;
    let out = '';
    rows.forEach((row, y) => {
        [...row].forEach((ch, x) => {
            if (ch !== '#' && ch !== '+') return;
            out += `<rect x="${x * cell}" y="${y * cell}" width="${cell}" height="${cell}" fill="${ch === '#' ? A : A2}"/>`;
        });
    });
    return `<g shape-rendering="crispEdges">${out}</g>`;
}
