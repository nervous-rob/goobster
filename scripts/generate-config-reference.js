#!/usr/bin/env node
/**
 * Generate documentation/config_reference.md from the field catalog.
 *
 *   node scripts/generate-config-reference.js          # rewrite the file
 *   node scripts/generate-config-reference.js --check  # exit 1 when the file is stale
 *
 * The catalog (packages/core/config/fieldCatalog.js) is the one description
 * of every installation setting; this page is its rendering, so a setting
 * cannot be added, renamed or re-defaulted without the reference changing in
 * the same commit. No database, no network, no config.json.
 */

const fs = require('node:fs');
const path = require('node:path');

const catalog = require('@goobster/core/config/fieldCatalog');
const probes = require('@goobster/core/services/providerProbeService');

const TARGET = path.join(__dirname, '..', 'documentation', 'config_reference.md');

const cell = (text) => String(text).replace(/\|/g, '\\|').replace(/\r?\n/g, ' ').trim();
const code = (text) => `\`${cell(text)}\``;

function defaultOf(field) {
    if (field.secret) return 'none';
    if (field.default === null || field.default === undefined) return 'unset';
    return code(JSON.stringify(field.default));
}

function whereOf(field) {
    const parts = [];
    if (field.env.length > 0) parts.push(`env ${field.env.map(code).join(', ')}`);
    const file = catalog.filePath(field);
    if (file) parts.push(`config.json ${code(file)}`);
    if (field.dbOverride) {
        parts.push(field.dbOverride.wins
            ? `database ${code(`${field.dbOverride.key}.${field.dbOverride.field}`)} (wins)`
            : `database ${code(`${field.dbOverride.key}.${field.dbOverride.field}`)}`);
    }
    return parts.join('<br>');
}

function precedenceOf(field) {
    if (field.dbOverride && field.dbOverride.wins) return 'database, then environment, then config.json, then default';
    if (field.sources.length === 1 && field.sources[0] === 'db') return 'database only';
    return 'environment, then config.json, then default';
}

function render() {
    const lines = [];
    lines.push('---');
    lines.push('title: Configuration reference (generated)');
    lines.push('kind: reference');
    lines.push('summary: Every installation setting Goobster reads - its environment variable, config.json path, type, default, whether a change is hot or needs a restart, which feature needs it and what it does - generated from the field catalog, plus the provider connection checks the manager can run.');
    lines.push('when: Looking up what a setting is called, where it can be set, what it defaults to, whether changing it needs a restart, or what a provider connection check sends and where.');
    lines.push('tags: [configuration, reference, settings, environment, config.json, secrets, probes, manager]');
    lines.push('---');
    lines.push('');
    lines.push('# Configuration reference');
    lines.push('');
    lines.push('Generated by `node scripts/generate-config-reference.js` from `packages/core/config/fieldCatalog.js`; do not edit it by hand (`npm run docs:check` fails when it is stale).');
    lines.push('How the manager reads, shows and changes these settings is in `documentation/manager_configuration.md`; the general setup guide is `documentation/configuration.md`.');
    lines.push('');
    lines.push('Precedence, unless a row says otherwise: environment variable, then `config.json`, then the default. A secret is never shown: the manager reports only whether it is set, where it comes from and its last four characters. "Restart" means the setting is read when a process starts; "hot" means it is read per request.');
    lines.push('');
    for (const section of catalog.SECTIONS) {
        const fields = catalog.inSection(section.id);
        if (fields.length === 0) continue;
        lines.push(`## ${section.title}`);
        lines.push('');
        lines.push('| Setting | Type | Where | Default | Applies | Needed by | What it does |');
        lines.push('| --- | --- | --- | --- | --- | --- | --- |');
        for (const field of fields) {
            const needed = [field.feature, ...field.alsoFeatures].join(', ');
            const type = field.secret ? 'secret' : field.type;
            const description = field.description + (precedenceOf(field).startsWith('database') ? ` Precedence: ${precedenceOf(field)}.` : '');
            lines.push(`| ${code(field.id)} | ${type} | ${whereOf(field) || 'none'} | ${defaultOf(field)} | ${field.apply === 'hot' ? 'hot' : 'restart'} | ${cell(needed)} | ${cell(description)} |`);
        }
        lines.push('');
    }
    lines.push('## Provider connection checks');
    lines.push('');
    lines.push('A check runs only when an operator asks for it (`POST /manager/api/config/probe`); nothing runs on a status or page load. Each check authenticates and reads one cheap, unbilled resource; none generates anything.');
    lines.push('');
    lines.push('| Target | What it does | Credential goes to |');
    lines.push('| --- | --- | --- |');
    for (const target of probes.describeTargets()) {
        lines.push(`| ${code(target.target)} | ${cell(target.whatItDoes)} | ${target.sendsCredentialTo ? code(target.sendsCredentialTo) : 'nowhere (no credential is sent)'} |`);
    }
    lines.push('');
    return `${lines.join('\n')}`;
}

function main(argv = process.argv.slice(2)) {
    const text = render();
    if (argv.includes('--check')) {
        let current = null;
        try {
            current = fs.readFileSync(TARGET, 'utf8');
        } catch { }
        if (current !== text) {
            console.error('documentation/config_reference.md is out of date. Run: node scripts/generate-config-reference.js');
            return 1;
        }
        console.log('documentation/config_reference.md is up to date.');
        return 0;
    }
    fs.writeFileSync(TARGET, text);
    console.log(`Wrote documentation/config_reference.md (${catalog.list().length} settings).`);
    return 0;
}

if (require.main === module) process.exitCode = main();

module.exports = { render, main };
